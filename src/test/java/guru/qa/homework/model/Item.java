package guru.qa.homework.model;

public class Item {
    private Integer productId;
    private String name;
    private Integer quantity;
    private Double price;

    public Integer getProductId() {
        return productId;
    }

    public String getName() {
        return name;
    }

    public Integer getQuantity() {
        return quantity;
    }

    public Double getPrice() {
        return price;
    }
}
